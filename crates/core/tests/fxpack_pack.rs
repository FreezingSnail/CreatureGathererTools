#[test]
fn unresolved_entry_writes_no_outputs() {
    let missing =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/testdata/fxpack/pack/missing.bin");
    let spec = LayoutSpec {
        entries: vec![Entry {
            name: Some("missing".to_owned()),
            namespace: None,
            source: Source::Raw(missing),
            align: None,
        }],
        save: None,
    };
    let output = TestDir::new();
    let result = pack::pack(
        &spec,
        &[],
        &output.path().join("dist"),
        &output.path().join("fxdata.h"),
    );

    let error = format!(
        "{:#}",
        result.err().expect("pack must reject missing source")
    );
    assert!(error.contains("resolving entry \"missing\""));
    assert!(error.contains("missing.bin"));
    assert!(!output.path().exists());
}

#[test]
fn repeated_packs_are_byte_identical() {
    let spec = LayoutSpec::load(&fixture()).unwrap();
    let first = TestDir::new();
    let second = TestDir::new();
    let first_outcome = pack::pack(
        &spec,
        &builders(),
        &first.path().join("dist"),
        &first.path().join("fxdata.h"),
    )
    .unwrap();
    let second_outcome = pack::pack(
        &spec,
        &builders(),
        &second.path().join("dist"),
        &second.path().join("fxdata.h"),
    )
    .unwrap();

    assert_eq!(
        std::fs::read(first_outcome.artifacts.dev_bin).unwrap(),
        std::fs::read(second_outcome.artifacts.dev_bin).unwrap()
    );
    assert_eq!(
        std::fs::read(first_outcome.header).unwrap(),
        std::fs::read(second_outcome.header).unwrap()
    );
}

#[test]
fn plan_resolves_padded_namespaced_image_and_save_fields_without_artifacts() {
    let fixture = TestDir::new();
    let source_dir = fixture.path().join("sources");
    std::fs::create_dir_all(&source_dir).unwrap();
    let raw_path = source_dir.join("raw.bin");
    std::fs::write(&raw_path, [0x10, 0x20]).unwrap();
    let image_path = source_dir.join("tile.png");
    let file = File::create(&image_path).unwrap();
    let mut encoder = png::Encoder::new(file, 4, 8);
    encoder.set_color(png::ColorType::Grayscale);
    encoder.set_depth(png::BitDepth::Eight);
    encoder
        .write_header()
        .unwrap()
        .write_image_data(&[0; 4 * 8])
        .unwrap();

    let spec = LayoutSpec {
        entries: vec![
            Entry {
                name: Some("raw".to_owned()),
                namespace: Some("Data".to_owned()),
                source: Source::Raw(raw_path.clone()),
                align: None,
            },
            Entry {
                name: Some("tile".to_owned()),
                namespace: None,
                source: Source::Image {
                    path: image_path.clone(),
                    width: 4,
                    height: 8,
                    shades: 4,
                    spacing: 0,
                },
                align: Some(8),
            },
        ],
        save: Some(SaveSpec {
            sectors: 2,
            entries: vec![
                SaveEntry {
                    name: "save_main".to_owned(),
                    offset: 0,
                },
                SaveEntry {
                    name: "save_log".to_owned(),
                    offset: 4096,
                },
            ],
        }),
    };

    let plan = pack::plan(&spec, &[]).unwrap();
    assert_eq!(plan.offsets.data_len, 24);
    assert_eq!(plan.fields.len(), 4);
    assert_eq!(
        &plan.fields[0],
        &creaturevm::fxpack::layout::Field {
            name: "raw".to_owned(),
            namespace: Some("Data".to_owned()),
            addr: 0,
            source_len: 2,
            span: 8,
            kind: FieldKind::Bytes,
            in_save: false,
            source: FieldSource::Raw {
                path: raw_path.clone(),
            },
        }
    );
    assert_eq!(
        &plan.fields[1],
        &creaturevm::fxpack::layout::Field {
            name: "tile".to_owned(),
            namespace: None,
            addr: 8,
            source_len: 16,
            span: 16,
            kind: FieldKind::Image {
                frames: 1,
                width: 4,
                height: 8,
            },
            in_save: false,
            source: FieldSource::Image { path: image_path },
        }
    );
    assert_eq!(
        plan.fields[2].source,
        FieldSource::Save,
        "save fields have no layout source path"
    );
    assert_eq!(
        (
            plan.fields[2].addr,
            plan.fields[2].source_len,
            plan.fields[2].span,
            plan.fields[2].in_save
        ),
        (0, 0, 4096, true)
    );
    assert_eq!(
        (
            plan.fields[3].addr,
            plan.fields[3].source_len,
            plan.fields[3].span,
            plan.fields[3].in_save
        ),
        (4096, 0, 4096, true)
    );
    assert!(!fixture.path().join("artifacts").exists());
}

#[test]
fn expanded_source_matches_equivalent_hand_entries() {
    let expanded = LayoutSpec::load(&pack_fixture("expand_layout.toml")).unwrap();
    let equivalent = LayoutSpec::load(&pack_fixture("expand_equivalent_layout.toml")).unwrap();

    let expanded_plan = pack::plan(&expanded, &[]).unwrap();
    let equivalent_plan = pack::plan(&equivalent, &[]).unwrap();

    let expanded_fields = expanded_plan
        .fields
        .iter()
        .map(|field| {
            (
                field.namespace.as_deref(),
                field.name.as_str(),
                field.addr,
                field.source_len,
                field.span,
                &field.kind,
                field.in_save,
                &field.source,
            )
        })
        .collect::<Vec<_>>();
    let equivalent_fields = equivalent_plan
        .fields
        .iter()
        .map(|field| {
            (
                field.namespace.as_deref(),
                field.name.as_str(),
                field.addr,
                field.source_len,
                field.span,
                &field.kind,
                field.in_save,
                &field.source,
            )
        })
        .collect::<Vec<_>>();

    assert_eq!(expanded_fields, equivalent_fields);
    assert_eq!(expanded_plan.bytes, equivalent_plan.bytes);
    assert!(matches!(
        expanded_plan.fields[0].source,
        FieldSource::CArray { .. }
    ));
    assert!(matches!(
        expanded_plan.fields[1].source,
        FieldSource::Symbol { .. }
    ));
    assert_eq!(
        &expanded_plan.bytes[..12],
        [0x10, 0x21, 0, 0, 0, 0, 0, 0, 0x12, 0x34, 0x56, 0x78]
    );
}

#[test]
fn real_old_and_expand_layouts_remain_strictly_equivalent() {
    let fixtures = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../../CreatureGathererFX/tools/tests/fixtures");
    let old = LayoutSpec::load(&fixtures.join("fxlayout-old-304.toml")).unwrap();
    let expanded = LayoutSpec::load(&fixtures.join("fxlayout-expand-20.toml")).unwrap();

    creaturevm::fxpack::equivalence::assert_equivalent(
        &pack::plan(&old, &[]).unwrap(),
        &pack::plan(&expanded, &[]).unwrap(),
    )
    .unwrap();
}
