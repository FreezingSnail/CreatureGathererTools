use creaturevm::fxpack::{
    pack::{self, BuilderBytes},
    spec::{Entry, LayoutSpec, Source},
};
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};

static NEXT_DIR: AtomicUsize = AtomicUsize::new(0);

struct TestDir(PathBuf);

impl TestDir {
    fn new() -> Self {
        let suffix = NEXT_DIR.fetch_add(1, Ordering::Relaxed);
        Self(std::env::temp_dir().join(format!(
            "creaturevm-fxpack-pack-{}-{suffix}",
            std::process::id()
        )))
    }

    fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TestDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn fixture() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/testdata/fxpack/pack/layout.toml")
}

fn builders() -> [BuilderBytes<'static>; 1] {
    [BuilderBytes {
        key: "built",
        bytes: vec![0x30, 0x40, 0x50],
        namespace: None,
    }]
}

#[test]
fn packs_raw_and_builder_entries_in_order() {
    let spec = LayoutSpec::load(&fixture()).unwrap();
    let output = TestDir::new();
    let outcome = pack::pack(
        &spec,
        &builders(),
        &output.path().join("dist"),
        &output.path().join("include/fxdata.h"),
    )
    .unwrap();

    assert_eq!(
        std::fs::read(&outcome.artifacts.data_bin).unwrap(),
        [0x10, 0x20, 0x30, 0x40, 0x50]
    );
    assert!(outcome.artifacts.save_bin.is_none());
    assert_eq!(outcome.fields.len(), 2);
    assert_eq!(outcome.fields[0].namespace.as_deref(), Some("Data"));
    assert_eq!(outcome.fields[1].addr, 2);
    assert_eq!(
        std::fs::read_to_string(&outcome.header).unwrap(),
        "#pragma once\n\n\
/**** FX data header generated by cgfx-tools ****/\n\n\
using uint24_t = __uint24;\n\n\
// Initialize FX hardware using  FX::begin(FX_DATA_PAGE); in the setup() function.\n\n\
constexpr uint16_t FX_DATA_PAGE  = 0xFFFF;\n\
constexpr uint24_t FX_DATA_BYTES = 5;\n\n\
namespace Data\n{\n  constexpr uint24_t rawData = 0x000000;\n}\n\
constexpr uint24_t builtData = 0x000002;\n"
    );
}

#[test]
fn unknown_builder_key_lists_available_keys_before_writing() {
    let spec = LayoutSpec::load(&fixture()).unwrap();
    let output = TestDir::new();
    let result = pack::pack(
        &spec,
        &[BuilderBytes {
            key: "other",
            bytes: vec![],
            namespace: None,
        }],
        &output.path().join("dist"),
        &output.path().join("fxdata.h"),
    );

    let error = result
        .err()
        .expect("pack must reject unknown builder")
        .to_string();
    assert!(error.contains("unknown builder key \"built\""));
    assert!(error.contains("available: [\"other\"]"));
    assert!(!output.path().exists());
}

#[test]
fn unused_builder_key_errors_before_writing() {
    let spec = LayoutSpec::load(&fixture()).unwrap();
    let output = TestDir::new();
    let result = pack::pack(
        &spec,
        &[
            BuilderBytes {
                key: "built",
                bytes: vec![],
                namespace: None,
            },
            BuilderBytes {
                key: "extra",
                bytes: vec![],
                namespace: None,
            },
        ],
        &output.path().join("dist"),
        &output.path().join("fxdata.h"),
    );

    assert!(
        result
            .err()
            .expect("pack must reject unused builder")
            .to_string()
            .contains("unused builder key \"extra\"")
    );
    assert!(!output.path().exists());
}

#[test]
fn unresolved_entry_writes_no_outputs() {
    let missing =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/testdata/fxpack/pack/missing.bin");
    let spec = LayoutSpec {
        entries: vec![Entry {
            name: "missing".to_owned(),
            namespace: None,
            source: Source::Raw(missing),
            align: None,
        }],
        save: None,
    };
    let output = TestDir::new();
    let result = pack::pack(
        &spec,
        &[],
        &output.path().join("dist"),
        &output.path().join("fxdata.h"),
    );

    let error = format!(
        "{:#}",
        result.err().expect("pack must reject missing source")
    );
    assert!(error.contains("resolving entry \"missing\""));
    assert!(error.contains("missing.bin"));
    assert!(!output.path().exists());
}

#[test]
fn repeated_packs_are_byte_identical() {
    let spec = LayoutSpec::load(&fixture()).unwrap();
    let first = TestDir::new();
    let second = TestDir::new();
    let first_outcome = pack::pack(
        &spec,
        &builders(),
        &first.path().join("dist"),
        &first.path().join("fxdata.h"),
    )
    .unwrap();
    let second_outcome = pack::pack(
        &spec,
        &builders(),
        &second.path().join("dist"),
        &second.path().join("fxdata.h"),
    )
    .unwrap();

    assert_eq!(
        std::fs::read(first_outcome.artifacts.dev_bin).unwrap(),
        std::fs::read(second_outcome.artifacts.dev_bin).unwrap()
    );
    assert_eq!(
        std::fs::read(first_outcome.header).unwrap(),
        std::fs::read(second_outcome.header).unwrap()
    );
}
