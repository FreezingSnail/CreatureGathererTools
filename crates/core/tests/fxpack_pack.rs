use creaturevm::fxpack::{
    layout::{FieldKind, FieldSource},
    pack::{self, BuilderBytes},
    spec::{Entry, LayoutSpec, SaveEntry, SaveSpec, Source},
};
use std::fs::File;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};

static NEXT_DIR: AtomicUsize = AtomicUsize::new(0);

struct TestDir(PathBuf);

impl TestDir {
    fn new() -> Self {
        let suffix = NEXT_DIR.fetch_add(1, Ordering::Relaxed);
        Self(std::env::temp_dir().join(format!(
            "creaturevm-fxpack-pack-{}-{suffix}",
            std::process::id()
        )))
    }

    fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TestDir {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn fixture() -> PathBuf {
    pack_fixture("layout.toml")
}

fn pack_fixture(name: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/testdata/fxpack/pack")
        .join(name)
}

fn builders() -> [BuilderBytes<'static>; 3] {
    [
        BuilderBytes {
            key: "menu_special",
            bytes: vec![0x30, 0x40, 0x50],
            namespace: None,
        },
        BuilderBytes {
            key: "global_special",
            bytes: vec![0x60],
            namespace: None,
        },
        BuilderBytes {
            key: "nested_special",
            bytes: vec![0x70, 0x80],
            namespace: None,
        },
    ]
}

#[test]
fn packs_raw_and_builder_entries_in_order() {
    let spec = LayoutSpec::load(&fixture()).unwrap();
    let output = TestDir::new();
    let outcome = pack::pack(
        &spec,
        &builders(),
        &output.path().join("dist"),
        &output.path().join("include/fxdata.h"),
    )
    .unwrap();

    assert_eq!(
        std::fs::read(&outcome.artifacts.data_bin).unwrap(),
        [0x10, 0x20, 0x30, 0x40, 0x50, 0x60, 0x70, 0x80]
    );
    assert!(outcome.artifacts.save_bin.is_none());
    assert_eq!(outcome.fields.len(), 4);
    assert_eq!(
        outcome
            .fields
            .iter()
            .map(|field| (field.namespace.as_deref(), field.name.as_str(), field.addr))
            .collect::<Vec<_>>(),
        [
            (Some("Teams::StockCreatures"), "rawData", 0),
            (Some("MenuFXData"), "special", 2),
            (None, "special", 5),
            (Some("MenuFXData::Nested"), "special", 6),
        ]
    );
    assert_eq!(
        std::fs::read_to_string(&outcome.header).unwrap(),
        "#pragma once\n\n\
/**** FX data header generated by cgfx-tools ****/\n\n\
using uint24_t = __uint24;\n\n\
// Initialize FX hardware using  FX::begin(FX_DATA_PAGE); in the setup() function.\n\n\
constexpr uint16_t FX_DATA_PAGE  = 0xffff;\n\
constexpr uint24_t FX_DATA_BYTES = 8;\n\n\
namespace Teams\n{\nnamespace StockCreatures\n{\n    constexpr uint24_t rawData = 0x000000;\n}\n}\n\n\
namespace MenuFXData\n{\n  constexpr uint24_t special = 0x000002;\n}\n\n\
constexpr uint24_t special = 0x000005;\n\
namespace MenuFXData\n{\nnamespace Nested\n{\n    constexpr uint24_t special = 0x000006;\n}\n}\n\n"
    );
}

#[test]
fn unknown_builder_key_lists_available_keys_before_writing() {
    let spec = LayoutSpec::load(&fixture()).unwrap();
    let output = TestDir::new();
    let result = pack::pack(
        &spec,
        &[BuilderBytes {
            key: "other",
            bytes: vec![],
            namespace: None,
        }],
        &output.path().join("dist"),
        &output.path().join("fxdata.h"),
    );

    let error = result
        .err()
        .expect("pack must reject unknown builder")
        .to_string();
    assert!(error.contains("unknown builder key \"menu_special\""));
    assert!(error.contains("available: [\"other\"]"));
    assert!(!output.path().exists());
}

