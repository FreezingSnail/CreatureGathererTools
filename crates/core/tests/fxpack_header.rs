use creaturevm::fxpack::header::render;
use creaturevm::fxpack::layout::{Field, FieldKind, Offsets};

fn offsets(data_page: u16, data_len: u32, save_page: Option<u16>, save_len: u32) -> Offsets {
    Offsets {
        data_len,
        data_len_flash: data_len,
        save_len,
        save_len_flash: save_len,
        data_page,
        save_page,
    }
}

fn bytes_field(name: &str, namespace: Option<&str>, addr: u32) -> Field {
    Field {
        name: name.to_owned(),
        namespace: namespace.map(str::to_owned),
        addr,
        len: 1,
        kind: FieldKind::Bytes,
        in_save: false,
    }
}

#[test]
fn renders_bytes_fields_without_namespace() {
    let fields = [
        bytes_field("first", None, 0),
        bytes_field("second", None, 0x48),
    ];
    let actual = render(&fields, &offsets(0xF6B2, 72, None, 0));

    assert_eq!(
        actual,
        "#pragma once\n\n\
/**** FX data header generated by cgfx-tools ****/\n\n\
using uint24_t = __uint24;\n\n\
// Initialize FX hardware using  FX::begin(FX_DATA_PAGE); in the setup() function.\n\n\
constexpr uint16_t FX_DATA_PAGE  = 0xF6B2;\n\
constexpr uint24_t FX_DATA_BYTES = 72;\n\n\
constexpr uint24_t first = 0x000000;\n\
constexpr uint24_t second = 0x000048;\n"
    );
}

#[test]
fn renders_image_metadata_triple() {
    let fields = [Field {
        name: "fontTrimmed".to_owned(),
        namespace: None,
        addr: 0x054B0A,
        len: 0,
        kind: FieldKind::Image {
            frames: 75,
            width: 5,
            height: 6,
        },
        in_save: false,
    }];

    let actual = render(&fields, &offsets(0xF6B2, 1, None, 0));
    assert!(actual.ends_with(
        "constexpr uint24_t fontTrimmed = 0x054B0A;\n\
constexpr uint16_t fontTrimmedWidth  = 5;\n\
constexpr uint16_t fontTrimmedHeight = 6;\n\
constexpr uint8_t  fontTrimmedFrames = 75;\n"
    ));
}

#[test]
fn opens_and_closes_namespace_blocks() {
    let fields = [
        bytes_field("one", Some("CreatureData"), 0x1D7),
        bytes_field("two", Some("CreatureData"), 0x200),
        bytes_field("three", None, 0x300),
    ];

    let actual = render(&fields, &offsets(0x1234, 0x301, None, 0));
    assert!(actual.contains(
        "namespace CreatureData\n{\n  constexpr uint24_t one = 0x0001D7;\n  constexpr uint24_t two = 0x000200;\n}\nconstexpr uint24_t three = 0x000300;\n"
    ));
}

#[test]
fn renders_optional_save_constants() {
    let fields = [bytes_field("save", None, 0)];
    let without_save = render(&fields, &offsets(0xFFFF, 1, None, 0));
    assert!(!without_save.contains("FX_SAVE_PAGE"));
    assert!(!without_save.contains("FX_SAVE_BYTES"));

    let with_save = render(&fields, &offsets(0xFFF0, 1, Some(0xF000), 17));
    assert!(with_save.contains("constexpr uint16_t FX_SAVE_PAGE  = 0xF000;\n"));
    assert!(with_save.contains("constexpr uint24_t FX_SAVE_BYTES = 17;\n"));
}

#[test]
fn formats_hex_uppercase_and_zero_padded() {
    let fields = [bytes_field("value", None, 0xABCDEF)];
    let actual = render(&fields, &offsets(0x00AF, 1, None, 0));

    assert!(actual.contains("constexpr uint16_t FX_DATA_PAGE  = 0x00AF;"));
    assert!(actual.contains("constexpr uint24_t value = 0xABCDEF;"));
}
