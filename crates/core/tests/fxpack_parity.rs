use creaturevm::fxpack::parity;

#[test]
fn normalize_header_drops_banner_and_blanks() {
    let header = "#pragma once\n\n/**** FX data header generated by fxdata-build.py tool version 1.15 ****/\n\nusing uint24_t = __uint24;\nconstexpr uint16_t FX_DATA_PAGE = 0xFF00;\n";
    let lines = parity::normalize_header(header);
    assert!(!lines.iter().any(|l| l.contains("generated by")));
    assert!(lines.contains(&"#pragma once"));
    assert!(lines.contains(&"constexpr uint16_t FX_DATA_PAGE = 0xFF00;"));
}

#[test]
fn first_difference_reports_correct_offset() {
    let a = vec![0x00, 0x01, 0x02, 0x03];
    let b = vec![0x00, 0x01, 0xFF, 0x03];
    assert_eq!(parity::first_difference(&a, &b), Some((2, 0x02, 0xFF)));
}

#[test]
fn first_difference_returns_none_for_equal() {
    let a = vec![1, 2, 3];
    assert_eq!(parity::first_difference(&a, &a), None);
}

#[test]
fn verify_pack_parity_succeeds_for_identical_inputs() {
    let header = "#pragma once\n\n/**** banner ****/\n\nconstexpr uint16_t X = 1;\n";
    let normalized = parity::normalize_header(header);
    assert_eq!(normalized, parity::normalize_header(header));
}

#[test]
fn parity_normalizes_hex_literal_case_only() {
    let upper =
        "constexpr uint16_t FX_DATA_PAGE  = 0xF6B2;\nconstexpr uint24_t first = 0x00ABCD;\n";
    let lower =
        "constexpr uint16_t FX_DATA_PAGE  = 0xf6b2;\nconstexpr uint24_t first = 0x00abcd;\n";

    assert_eq!(
        parity::normalize_header_for_parity(upper),
        parity::normalize_header_for_parity(lower)
    );
}

#[test]
fn parity_keeps_numeric_values_and_field_order_strict() {
    let expected = "constexpr uint16_t FX_DATA_PAGE = 0xF6B2;\nconstexpr uint24_t first = 0x000001;\nconstexpr uint24_t second = 0x000002;\n";
    let changed_value = "constexpr uint16_t FX_DATA_PAGE = 0xF6B2;\nconstexpr uint24_t first = 0x000001;\nconstexpr uint24_t second = 0x000003;\n";
    let reordered = "constexpr uint16_t FX_DATA_PAGE = 0xF6B2;\nconstexpr uint24_t second = 0x000002;\nconstexpr uint24_t first = 0x000001;\n";

    assert_ne!(
        parity::normalize_header_for_parity(expected),
        parity::normalize_header_for_parity(changed_value)
    );
    assert_ne!(
        parity::normalize_header_for_parity(expected),
        parity::normalize_header_for_parity(reordered)
    );
}

