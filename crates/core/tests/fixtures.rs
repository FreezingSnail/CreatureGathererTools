use creaturevm::arena::parse_arena_csv;
use creaturevm::builder::load_opponents_csv;
use creaturevm::config::Config;
use creaturevm::fixtures::{FixtureProject, emit_fixtures};
use creaturevm::store::Store;
use std::fs;
use std::path::PathBuf;

const TESTDATA: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/testdata");

fn read(name: &str) -> String {
    fs::read_to_string(format!("{TESTDATA}/builder_out/fixtures/{name}"))
        .expect("fixture header must be emitted")
}

#[test]
fn emitted_headers_are_model_derived_and_device_structural() {
    let cfg = Config::load_from(format!("{TESTDATA}/creature-tools.json"))
        .expect("test project config parses");
    let store = Store::new(&cfg);
    let creatures = store.load_creatures().expect("creature model parses");
    let mut moves = store.load_moves().expect("move model parses");
    let opponents =
        load_opponents_csv(format!("{TESTDATA}/opponents.csv")).expect("opponent model parses");
    let arena = parse_arena_csv(format!("{TESTDATA}/arena.csv")).expect("arena model parses");

    // Mutating parsed data before emission proves the emitter does not re-dump
    // any writer artifact: both the packed word and field expectation change.
    moves[0].power = 31;
    let destination = PathBuf::from(format!("{TESTDATA}/builder_out/fixtures"));
    emit_fixtures(
        &FixtureProject {
            creatures: &creatures,
            moves: &moves,
            opponents: &opponents,
            arena: &arena,
        },
        &destination,
    )
    .expect("fixtures emit");

    for header in [
        "creature_data.hpp",
        "move_data.hpp",
        "opponent_data.hpp",
        "arena_data.hpp",
        "rawread_data.hpp",
    ] {
        assert!(read(header).starts_with("// Generated by cgfx-tools - do not edit.\n"));
    }

    let creatures = read("creature_data.hpp");
    assert!(creatures.contains("const CreatureData_t creatureFixtures[] PROGMEM"));
    assert!(creatures.contains("{ 0, 2, 15, 8, 3, 3, 2, 2, 3, 3, 8, 32, 32, 32 }"));

    let moves = read("move_data.hpp");
    assert!(moves.contains("0x0F80FFFFUL"));
    assert!(moves.contains("{ 0, 31, 0, 0, 255, 255 }"));

    let opponents = read("opponent_data.hpp");
    assert!(opponents.contains("const OpponentSeed opponentSeeds[] PROGMEM"));
    assert!(opponents.contains("{ 0, 31, 0xFFFF0100UL }"));

    let arena = read("arena_data.hpp");
    assert!(arena.contains("const uint8_t arenaFixtures[][5] PROGMEM"));
    assert!(arena.contains("{ 0, 8, 32, 32, 32 }"));
    assert!(arena.contains("Parsed arena model contains 2 teamList entries"));

    let rawread = read("rawread_data.hpp");
    assert!(rawread.contains("fxdata symbol move_table + 0x000000"));
    assert!(rawread.contains("fxdata symbol opponent_seeds + 0x000000"));
    assert!(rawread.contains("constexpr uint16_t rawReadMoveTableFirst = 0x800F"));
    assert!(rawread.contains("constexpr OpponentSeed rawReadOpponentSeed"));
}
