use creaturevm::arena::parse_arena_csv;
use creaturevm::builder;
use creaturevm::builder::load_opponents_csv;
use creaturevm::config::Config;
use creaturevm::fixtures::{FixtureProject, emit_fixtures};
use creaturevm::model::ScriptObject;
use creaturevm::store::Store;
use std::fs;

const TESTDATA: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/testdata");

fn read(name: &str) -> String {
    fs::read_to_string(
        std::env::temp_dir()
            .join(format!("cgfx-tools-fixtures-{}", std::process::id()))
            .join(name),
    )
    .expect("fixture header must be emitted")
}

#[test]
fn emitted_headers_are_model_derived_and_device_structural() {
    let cfg = Config::load_from(format!("{TESTDATA}/creature-tools.json"))
        .expect("test project config parses");
    let store = Store::new(&cfg);
    let mut creatures = store.load_creatures().expect("creature model parses");
    let mut map = store.load_map().expect("tracked map model parses");
    map.width = 16;
    map.height = 5;
    map.tiles.resize(5, vec![0; 16]);
    for row in &mut map.tiles {
        row.resize(16, 0);
    }
    map.tiles[0][0] = 1;
    map.tiles[0][1] = 527;
    map.tiles[0][2] = 1023;
    map.tile_properties.insert(527, 0b000011);
    map.tile_properties.insert(1023, 0b110000);
    map.npcs.clear();
    map.scripts = [0u16, 32, 33]
        .iter()
        .map(|&chunk| ScriptObject {
            id: i32::from(chunk),
            x: i32::from((chunk % 32) * 8),
            y: i32::from((chunk / 32) * 4),
            script: "msg {fixture}".into(),
        })
        .collect();
    let script_bytes = builder::build_map(&map)
        .expect("fixture map builds")
        .scripts_bin;
    let opponents =
        load_opponents_csv(format!("{TESTDATA}/opponents.csv")).expect("opponent model parses");
    let arena = parse_arena_csv(format!("{TESTDATA}/arena.csv")).expect("arena model parses");

    // Mutating parsed data before emission proves the emitter does not re-dump
    // any writer artifact: the emitted creature row must reflect the change.
    creatures[0].atk = 31;
    let destination =
        std::env::temp_dir().join(format!("cgfx-tools-fixtures-{}", std::process::id()));
    emit_fixtures(
        &FixtureProject {
            creatures: &creatures,
            opponents: &opponents,
            arena: &arena,
            map: &map,
            scripts: &script_bytes,
        },
        &destination,
    )
    .expect("fixtures emit");

    for header in [
        "creature_data.hpp",
        "opponent_data.hpp",
        "arena_data.hpp",
        "rawread_data.hpp",
        "map_data.hpp",
        "script_data.hpp",
    ] {
        assert!(read(header).starts_with("// Generated by cgfx-tools - do not edit.\n"));
    }

    let creature = read("creature_data.hpp");
    assert!(creature.contains("const CreatureData_t creatureFixtures[] PROGMEM"));
    assert!(creature.contains("{ 0, 2, 15, 8, 31, 3, 2, 2, 3, 3, 2 }"));
    assert!(creature.contains("{ 99, 15, 15, 1, 1, 1, 1, 1, 1, 1, 1 }"));

    let opponents = read("opponent_data.hpp");
    assert!(opponents.contains("const OpponentSeed opponentSeeds[] PROGMEM"));
    assert!(opponents.contains("{ 0, 31, 1 }"));
    assert!(opponents.contains("{ 255, 0, 0 }"));
    assert!(opponents.contains("{ 29, 255, 0 }"));

    let arena = read("arena_data.hpp");
    assert!(arena.contains("const uint8_t arenaFixtures[][2] PROGMEM"));
    assert!(arena.contains("{ 0, 2 }"));
    assert!(arena.contains("{ 99, 1 }"));
    assert!(arena.contains("Parsed arena model contains 2 teamList entries"));

    let rawread = read("rawread_data.hpp");
    assert!(rawread.contains("fxdata symbol opponent_seeds + 0x000000"));
    assert!(rawread.contains("constexpr OpponentSeed rawReadOpponentSeed"));
    assert!(rawread.contains("{ 0, 31, 1 }"));
    assert!(rawread.contains("constexpr uint16_t rawReadCursorFirstPage = 0;"));

    let map = read("map_data.hpp");
    assert!(map.contains("const MapWordFixture mapWordFixtures[] PROGMEM"));
    assert!(map.contains("{ 0, 0x0001 }"));
    assert!(map.contains("{ 1, 0x0E0F }"));
    assert!(map.contains("{ 2, 0xC3FF }"));
    assert!(map.contains("mapWordFixtureCount = 4"));

    let scripts = read("script_data.hpp");
    assert!(scripts.contains("scriptSlotFixtureCount = 3"));
    for chunk in [0, 32, 33] {
        assert!(scripts.contains(&format!("{{ {chunk}, {{")));
    }
    assert!(scripts.contains("{ 3, { 0x80, 0x01, 0x00 } }"));
    assert!(scripts.contains("{ 512, { 0x00, 0x00, 0x01 } }"));
    assert!(scripts.contains("{ 2047, { 0x80, 0xFF, 0x03 } }"));
    // Pinned GiveItem opcode-9 stream fixture (contract 2026-10-12).
    assert!(scripts.contains(
        "const uint8_t giveItemStreamFixture[] PROGMEM = { 9, 0, 23, 99, 255 };"
    ));
    assert!(scripts.contains("giveItemStreamFixtureCount = 5"));
}

/// The generator's pinned GiveItem fixture stream must equal the canonical AST
/// encoder output for the same command, so the emitted device fixture and the
/// writer cannot drift.
#[test]
fn giveitem_fixture_stream_matches_encoder() {
    use creaturevm::processor::ast::{Cmd, ToBytecode};
    let encoded = Cmd::GiveItem {
        kind: 0,
        id: 23,
        count: 99,
    }
    .to_bytes();
    assert_eq!(encoded, vec![9, 0, 23, 99]);
    let mut stream = encoded;
    stream.push(255); // End sentinel
    assert_eq!(stream, vec![9, 0, 23, 99, 255]);
}
