//! Device-test fixture emission.
//!
//! These headers deliberately consume parsed domain values, never the byte
//! vectors produced by the artifact writers. Device tests therefore compare
//! the FX reader against source-model truth rather than against its writer.

use crate::arena::ArenaEntry;
use crate::builder::BuildError;
use crate::model::{Creature, Move, OpponentSeed};
use std::path::Path;

const BANNER: &str = "// Generated by cgfx-tools - do not edit.\n";

/// Parsed game-data values used by the device-test fixture emitter.
///
/// `arena` records are retained as parsed project model input. Stock-creature
/// fixture rows come from the creature model because `arenaLoad` addresses the
/// `Teams::StockCreatures` records, which are the creature id plus four move
/// ids, rather than `teamList`'s address-valued arena rows.
pub struct FixtureProject<'a> {
    pub creatures: &'a [Creature],
    pub moves: &'a [Move],
    pub opponents: &'a [OpponentSeed],
    pub arena: &'a [ArenaEntry],
}

/// Emits all headers consumed by `tst/fxdatatest` into `dir`.
pub fn emit_fixtures(
    processed: &FixtureProject<'_>,
    dir: impl AsRef<Path>,
) -> Result<(), BuildError> {
    let dir = dir.as_ref();
    std::fs::create_dir_all(dir)
        .map_err(|error| BuildError(format!("creating {}: {error}", dir.display())))?;

    write(
        dir,
        "creature_data.hpp",
        creature_header(processed.creatures)?,
    )?;
    write(dir, "move_data.hpp", move_header(processed.moves)?)?;
    write(
        dir,
        "opponent_data.hpp",
        opponent_header(processed.opponents),
    )?;
    write(
        dir,
        "arena_data.hpp",
        arena_header(processed.creatures, processed.arena)?,
    )?;
    write(
        dir,
        "rawread_data.hpp",
        rawread_header(processed.moves, processed.opponents)?,
    )?;
    Ok(())
}

fn write(dir: &Path, name: &str, contents: String) -> Result<(), BuildError> {
    let path = dir.join(name);
    std::fs::write(&path, contents)
        .map_err(|error| BuildError(format!("writing {}: {error}", path.display())))
}

fn creature_type(ty: &str) -> Result<u8, BuildError> {
    match ty {
        "spirit" => Ok(0),
        "water" => Ok(1),
        "wind" => Ok(2),
        "earth" => Ok(3),
        "fire" => Ok(4),
        "lightning" => Ok(5),
        "plant" => Ok(6),
        "elder" => Ok(7),
        "status" => Ok(8),
        "none" => Ok(15),
        _ => Err(BuildError(format!("unknown fixture type {ty:?}"))),
    }
}

fn move_type(ty: &str) -> Result<u8, BuildError> {
    creature_type(ty)
}

fn accuracy(accuracy: i32) -> u8 {
    match accuracy {
        100 => 0,
        90 => 1,
        80 => 2,
        70 => 3,
        _ => 0,
    }
}

fn effect(effect: &str) -> u8 {
    match effect {
        "NONE" => 0xFF,
        "DPRSD" => 0,
        "SOAKED" => 1,
        "BUFTD" => 2,
        "SOILED" => 3,
        "SCRCHD" => 4,
        "ZAPPED" => 5,
        "TANGLD" => 6,
        "REDCD" => 7,
        "ENLTND" => 8,
        "DRNCHD" => 9,
        "AIRSWPT" => 10,
        "GRNDED" => 11,
        "KINDLD" => 12,
        "CHRGD" => 13,
        "ENRCHD" => 14,
        "EVOLVD" => 15,
        "ATKDWN" => 16,
        "DEFDWN" => 17,
        "SPCADWN" => 18,
        "SPCDDWN" => 19,
        "SPDDWN" => 20,
        "ATKUP" => 21,
        "DEFUP" => 22,
        "SPCAUP" => 23,
        "SPCDUP" => 24,
        "SPDUP" => 25,
        "SAPPD" => 26,
        "INFSED" => 27,
        "PINNED" => 28,
        "CONCUSED" => 29,
        _ => 0xFF,
    }
}

fn creature_header(creatures: &[Creature]) -> Result<String, BuildError> {
    let mut output = format!("{BANNER}#pragma once\n#include \"src/lib/DataTypes.hpp\"\n\n");
    output.push_str("// Model fixture; copy each CreatureData_t with memcpy_P.\n");
    output.push_str("const CreatureData_t creatureFixtures[] PROGMEM = {\n");
    for creature in creatures {
        output.push_str(&format!(
            "    {{ {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {} }},\n",
            creature.id,
            creature_type(&creature.type1)?,
            creature_type(&creature.type2)?,
            creature.evo_level,
            creature.atk,
            creature.def,
            creature.spc_atk,
            creature.spc_def,
            creature.hp,
            creature.spd,
            creature.move1,
            creature.move2,
            creature.move3,
            creature.move4,
        ));
    }
    output.push_str("};\n");
    output.push_str(&format!(
        "constexpr uint8_t creatureFixtureCount = {};\n",
        creatures.len()
    ));
    Ok(output)
}

fn move_bits(move_data: &Move) -> Result<(u8, u8, u8, u8, u8), BuildError> {
    let ty = move_type(&move_data.r#type)?;
    let power = u8::try_from(move_data.power)
        .map_err(|_| BuildError(format!("move {} power does not fit uint8_t", move_data.id)))?;
    let physical = u8::try_from(move_data.physical).map_err(|_| {
        BuildError(format!(
            "move {} physical does not fit uint8_t",
            move_data.id
        ))
    })?;
    Ok((
        ty,
        power,
        physical,
        accuracy(move_data.accuracy),
        effect(&move_data.effect),
    ))
}

fn move_word(move_data: &Move) -> Result<u32, BuildError> {
    let (ty, power, physical, accuracy, effect1) = move_bits(move_data)?;
    Ok((u32::from(ty) << 28)
        | (u32::from(power) << 23)
        | (u32::from(physical) << 22)
        | (u32::from(accuracy) << 20)
        | (u32::from(effect1) << 8)
        | 0xFF)
}

fn move_header(moves: &[Move]) -> Result<String, BuildError> {
    let mut output = format!("{BANNER}#pragma once\n#include \"src/lib/Move.hpp\"\n\n");
    output.push_str("// Model fixture; expectations are parsed move fields, not writer output.\n");
    output.push_str("const uint32_t moveFixtures[] PROGMEM = {\n");
    for move_data in moves {
        output.push_str(&format!("    0x{:08X}UL,\n", move_word(move_data)?));
    }
    output.push_str("};\n\nstruct MoveFixtureExpectation {\n");
    output.push_str("    uint8_t type, power, physical, accuracy, effect1, effect2;\n};\n");
    output.push_str("const MoveFixtureExpectation moveFixtureExpectations[] PROGMEM = {\n");
    for move_data in moves {
        let (ty, power, physical, acc, effect1) = move_bits(move_data)?;
        output.push_str(&format!(
            "    {{ {ty}, {power}, {physical}, {acc}, {effect1}, 255 }},\n"
        ));
    }
    output.push_str("};\n");
    output.push_str(&format!(
        "constexpr uint8_t moveFixtureCount = {};\n",
        moves.len()
    ));
    Ok(output)
}

fn opponent_header(opponents: &[OpponentSeed]) -> String {
    let mut output = format!("{BANNER}#pragma once\n#include \"src/lib/DataTypes.hpp\"\n\n");
    output.push_str("// Model fixture; copy each OpponentSeed with memcpy_P before comparing.\n");
    output.push_str("const OpponentSeed opponentSeeds[] PROGMEM = {\n");
    for seed in opponents {
        output.push_str("    {\n");
        for member in [seed.first, seed.second, seed.third] {
            output.push_str(&format!(
                "        {{ {}, {}, 0x{:08X}UL }},\n",
                member.creature_id, member.level, member.moves
            ));
        }
        output.push_str("    },\n");
    }
    output.push_str("};\n");
    output.push_str(&format!(
        "constexpr uint8_t opponentSeedCount = {};\n",
        opponents.len()
    ));
    output
}

fn arena_header(creatures: &[Creature], arena: &[ArenaEntry]) -> Result<String, BuildError> {
    let mut output = format!("{BANNER}#pragma once\n#include \"src/lib/DataTypes.hpp\"\n\n");
    output.push_str(
        "// Model fixture for Teams::StockCreatures; the first row is the null stock entry.\n",
    );
    output.push_str(&format!(
        "// Parsed arena model contains {} teamList entries.\n",
        arena.len()
    ));
    output.push_str("const uint8_t arenaFixtures[][5] PROGMEM = {\n    { 0, 0, 0, 0, 0 },\n");
    let mut stock: Vec<&Creature> = creatures.iter().collect();
    stock.sort_by_key(|creature| creature.id);
    for creature in stock {
        output.push_str(&format!(
            "    {{ {}, {}, {}, {}, {} }},\n",
            creature.id, creature.move1, creature.move2, creature.move3, creature.move4
        ));
    }
    output.push_str("};\n");
    output.push_str(&format!(
        "constexpr uint8_t arenaFixtureCount = {};\n",
        creatures.len() + 1
    ));
    Ok(output)
}

fn rawread_header(moves: &[Move], opponents: &[OpponentSeed]) -> Result<String, BuildError> {
    let first_move = moves
        .first()
        .ok_or_else(|| BuildError("fixtures require at least one move".into()))?;
    let first_opponent = opponents
        .first()
        .ok_or_else(|| BuildError("fixtures require at least one opponent".into()))?;
    let word = move_word(first_move)?;
    let packed = (word >> 16) as u16;
    let first = packed.rotate_left(8);
    let (_, _, _, _, effect1) = move_bits(first_move)?;
    let next = 0xFF00 | u16::from(effect1);
    let mut output = format!("{BANNER}#pragma once\n\n");
    output.push_str("// fxdata symbol move_table + 0x000000: first two bytes of parsed move 0.\n");
    output.push_str(&format!(
        "constexpr uint16_t rawReadMoveTableFirst = 0x{first:04X};\n"
    ));
    output.push_str(
        "// fxdata symbol move_table + 0x000002: effect1/effect2 bytes of parsed move 0.\n",
    );
    output.push_str(&format!(
        "constexpr uint16_t rawReadMoveTableNext = 0x{next:04X};\n\n"
    ));
    output.push_str("// fxdata symbol opponent_seeds + 0x000000: parsed opponent seed 0.\n");
    output.push_str("constexpr OpponentSeed rawReadOpponentSeed = {\n");
    for member in [
        first_opponent.first,
        first_opponent.second,
        first_opponent.third,
    ] {
        output.push_str(&format!(
            "    {{ {}, {}, 0x{:08X}UL }},\n",
            member.creature_id, member.level, member.moves
        ));
    }
    output.push_str("};\n\n");
    output.push_str("// fxdata symbol opponent_seeds + 0x000000: first FX data cursor page.\n");
    output.push_str("constexpr uint16_t rawReadCursorFirstPage = 0;\n");
    output.push_str("// fxdata symbol move_table + 0x000003: maximal cursor-page sentinel.\n");
    output.push_str("constexpr uint16_t rawReadCursorLastPage = UINT16_MAX;\n");
    Ok(output)
}
