//! Device-test fixture emission.
//!
//! These headers deliberately consume parsed domain values, never the byte
//! vectors produced by the artifact writers. Device tests therefore compare
//! the FX reader against source-model truth rather than against its writer.

use crate::arena::ArenaEntry;
use crate::builder::BuildError;
use crate::model::{attack_mask, Creature, GameMap, OpponentSeed};
use std::path::Path;

const BANNER: &str = "// Generated by cgfx-tools - do not edit.\n";

/// Parsed game-data values used by the device-test fixture emitter.
///
/// `arena` records are retained as parsed project model input. Stock-creature
/// fixture rows come from the creature model because `arenaLoad` addresses the
/// `Teams::StockCreatures` records, which are the creature id plus its folded
/// attack mask, rather than `teamList`'s address-valued arena rows.
pub struct FixtureProject<'a> {
    pub creatures: &'a [Creature],
    pub opponents: &'a [OpponentSeed],
    pub arena: &'a [ArenaEntry],
    pub map: &'a GameMap,
    pub scripts: &'a [u8],
}

/// Emits all headers consumed by `tst/fxdatatest` into `dir`.
pub fn emit_fixtures(
    processed: &FixtureProject<'_>,
    dir: impl AsRef<Path>,
) -> Result<(), BuildError> {
    let dir = dir.as_ref();
    std::fs::create_dir_all(dir)
        .map_err(|error| BuildError(format!("creating {}: {error}", dir.display())))?;

    write(
        dir,
        "creature_data.hpp",
        creature_header(processed.creatures)?,
    )?;
    write(
        dir,
        "opponent_data.hpp",
        opponent_header(processed.opponents),
    )?;
    write(
        dir,
        "arena_data.hpp",
        arena_header(processed.creatures, processed.arena)?,
    )?;
    write(dir, "rawread_data.hpp", rawread_header(processed.opponents)?)?;
    write(dir, "map_data.hpp", map_header(processed.map)?)?;
    write(dir, "script_data.hpp", script_header(processed.scripts)?)?;
    Ok(())
}

fn write(dir: &Path, name: &str, contents: String) -> Result<(), BuildError> {
    let path = dir.join(name);
    std::fs::write(&path, contents)
        .map_err(|error| BuildError(format!("writing {}: {error}", path.display())))
}

fn creature_type(ty: &str) -> Result<u8, BuildError> {
    match ty {
        "spirit" => Ok(0),
        "water" => Ok(1),
        "wind" => Ok(2),
        "earth" => Ok(3),
        "fire" => Ok(4),
        "lightning" => Ok(5),
        "plant" => Ok(6),
        "elder" => Ok(7),
        "status" => Ok(8),
        "none" => Ok(15),
        _ => Err(BuildError(format!("unknown fixture type {ty:?}"))),
    }
}

fn creature_header(creatures: &[Creature]) -> Result<String, BuildError> {
    let mut output = format!("{BANNER}#pragma once\n#include \"src/lib/DataTypes.hpp\"\n\n");
    output.push_str("// Model fixture; copy each CreatureData_t with memcpy_P.\n");
    output.push_str("const CreatureData_t creatureFixtures[] PROGMEM = {\n");
    for creature in creatures {
        output.push_str(&format!(
            "    {{ {}, {}, {}, {}, {}, {}, {}, {}, {}, {}, {} }},\n",
            creature.id,
            creature_type(&creature.type1)?,
            creature_type(&creature.type2)?,
            creature.evo_level,
            creature.atk,
            creature.def,
            creature.spc_atk,
            creature.spc_def,
            creature.hp,
            creature.spd,
            attack_mask(&creature.moves),
        ));
    }
    output.push_str("};\n");
    output.push_str(&format!(
        "constexpr uint8_t creatureFixtureCount = {};\n",
        creatures.len()
    ));
    Ok(output)
}

fn opponent_header(opponents: &[OpponentSeed]) -> String {
    let mut output = format!("{BANNER}#pragma once\n#include \"src/lib/DataTypes.hpp\"\n\n");
    output.push_str("// Model fixture; copy each OpponentSeed with memcpy_P before comparing.\n");
    output.push_str("const OpponentSeed opponentSeeds[] PROGMEM = {\n");
    for seed in opponents {
        output.push_str("    {\n");
        for member in [seed.first, seed.second, seed.third] {
            output.push_str(&format!(
                "        {{ {}, {}, {} }},\n",
                member.creature_id, member.level, member.attack_mask
            ));
        }
        output.push_str("    },\n");
    }
    output.push_str("};\n");
    output.push_str(&format!(
        "constexpr uint8_t opponentSeedCount = {};\n",
        opponents.len()
    ));
    output
}

fn arena_header(creatures: &[Creature], arena: &[ArenaEntry]) -> Result<String, BuildError> {
    let mut output = format!("{BANNER}#pragma once\n#include \"src/lib/DataTypes.hpp\"\n\n");
    output.push_str(
        "// Model fixture for Teams::StockCreatures; the first row is the null stock entry.\n",
    );
    output.push_str(&format!(
        "// Parsed arena model contains {} teamList entries.\n",
        arena.len()
    ));
    output.push_str("const uint8_t arenaFixtures[][2] PROGMEM = {\n    { 0, 0 },\n");
    let mut stock: Vec<&Creature> = creatures.iter().collect();
    stock.sort_by_key(|creature| creature.id);
    for creature in stock {
        output.push_str(&format!(
            "    {{ {}, {} }},\n",
            creature.id,
            attack_mask(&creature.moves)
        ));
    }
    output.push_str("};\n");
    output.push_str(&format!(
        "constexpr uint8_t arenaFixtureCount = {};\n",
        creatures.len() + 1
    ));
    Ok(output)
}

fn rawread_header(opponents: &[OpponentSeed]) -> Result<String, BuildError> {
    let first_opponent = opponents
        .first()
        .ok_or_else(|| BuildError("fixtures require at least one opponent".into()))?;
    let mut output = format!("{BANNER}#pragma once\n\n");
    output.push_str("// fxdata symbol opponent_seeds + 0x000000: parsed opponent seed 0.\n");
    output.push_str("constexpr OpponentSeed rawReadOpponentSeed = {\n");
    for member in [
        first_opponent.first,
        first_opponent.second,
        first_opponent.third,
    ] {
        output.push_str(&format!(
            "    {{ {}, {}, {} }},\n",
            member.creature_id, member.level, member.attack_mask
        ));
    }
    output.push_str("};\n\n");
    output.push_str("// fxdata symbol opponent_seeds + 0x000000: first FX data cursor page.\n");
    output.push_str("constexpr uint16_t rawReadCursorFirstPage = 0;\n");
    output.push_str("// Maximal cursor-page sentinel used by the FX reader contract.\n");
    output.push_str("constexpr uint16_t rawReadCursorLastPage = UINT16_MAX;\n");
    Ok(output)
}

#[derive(Clone, Copy)]
struct MapWordFixture {
    index: u16,
    word: u16,
}

fn map_header(map: &GameMap) -> Result<String, BuildError> {
    let mut selected = Vec::<MapWordFixture>::new();
    let mut seen = [false; 64];
    let mut ordinary = None;
    let mut high_id = None;
    for (y, row) in map.tiles.iter().enumerate() {
        for (x, &tile) in row.iter().enumerate() {
            if x >= 256 || y >= 256 {
                continue;
            }
            let props = if tile == 0 {
                0
            } else {
                map.tile_properties.get(&tile).copied().unwrap_or(0)
            };
            if props > 0x3F {
                return Err(BuildError(format!(
                    "map fixture tile ({x},{y}) has invalid property mask {props}"
                )));
            }
            let fixture = MapWordFixture {
                index: (y * 256 + x) as u16,
                word: tile | (u16::from(props) << 10),
            };
            if tile != 0 && props == 0 && ordinary.is_none() {
                ordinary = Some(fixture);
            }
            if tile > 511 && high_id.is_none() {
                high_id = Some(fixture);
            }
            if props != 0 && !seen[props as usize] {
                seen[props as usize] = true;
                selected.push(fixture);
            }
        }
    }
    let ordinary = ordinary
        .ok_or_else(|| BuildError("map fixtures require an ordinary non-empty cell".into()))?;
    let high_id =
        high_id.ok_or_else(|| BuildError("map fixtures require a tile id above 511".into()))?;
    selected.insert(0, high_id);
    selected.insert(0, ordinary);
    let mut output =
        format!("{BANNER}#pragma once\n#include <stdint.h>\n#include <avr/pgmspace.h>\n\n");
    output.push_str("struct MapWordFixture { uint16_t index; uint16_t word; };\n");
    output.push_str("const MapWordFixture mapWordFixtures[] PROGMEM = {\n");
    for fixture in &selected {
        output.push_str(&format!(
            "    {{ {}, 0x{:04X} }},\n",
            fixture.index, fixture.word
        ));
    }
    output.push_str("};\n");
    output.push_str(&format!(
        "constexpr uint8_t mapWordFixtureCount = {};\n",
        selected.len()
    ));
    Ok(output)
}

fn script_header(scripts: &[u8]) -> Result<String, BuildError> {
    const SLOT_BYTES: usize = 128;
    const SLOT_COUNT: usize = 2048;
    if scripts.len() != SLOT_BYTES * SLOT_COUNT {
        return Err(BuildError(format!(
            "script fixture image has {} bytes, expected {}",
            scripts.len(),
            SLOT_BYTES * SLOT_COUNT
        )));
    }
    let mut output =
        format!("{BANNER}#pragma once\n#include <stdint.h>\n#include <avr/pgmspace.h>\n\n");
    output.push_str("struct ScriptSlotFixture { uint16_t chunk; uint8_t prefix[4]; };\n");
    output.push_str("const ScriptSlotFixture scriptSlotFixtures[] PROGMEM = {\n");
    let mut count = 0u16;
    for chunk in 0..SLOT_COUNT {
        let slot = &scripts[chunk * SLOT_BYTES..(chunk + 1) * SLOT_BYTES];
        if slot.contains(&0xFF) {
            output.push_str(&format!(
                "    {{ {chunk}, {{ 0x{:02X}, 0x{:02X}, 0x{:02X}, 0x{:02X} }} }},\n",
                slot[0], slot[1], slot[2], slot[3]
            ));
            count += 1;
        }
    }
    output.push_str("};\n");
    output.push_str(&format!(
        "constexpr uint16_t scriptSlotFixtureCount = {count};\n"
    ));
    output.push_str("struct ScriptAddressFixture { uint16_t chunk; uint8_t offset[3]; };\n");
    output.push_str("const ScriptAddressFixture scriptAddressFixtures[] PROGMEM = {\n");
    for chunk in [3u16, 512, 2047] {
        let offset = u32::from(chunk) * SLOT_BYTES as u32;
        output.push_str(&format!(
            "    {{ {chunk}, {{ 0x{:02X}, 0x{:02X}, 0x{:02X} }} }},\n",
            offset as u8,
            (offset >> 8) as u8,
            (offset >> 16) as u8
        ));
    }
    output.push_str("};\nconstexpr uint8_t scriptAddressFixtureCount = 3;\n");
    // Pinned GiveItem opcode-9 stream (contract revision 2026-10-12): the
    // four-byte command (opcode + kind + id + count) followed by End. Kept as
    // a literal so device tests compare against the ABI rather than writer
    // output; the native parity test pins the encoder to these bytes.
    output.push_str(
        "// Pinned GiveItem opcode-9 stream: GiveItem(kind=lure=0, id=23, count=99) + End.\n\
         const uint8_t giveItemStreamFixture[] PROGMEM = { 9, 0, 23, 99, 255 };\n\
         constexpr uint8_t giveItemStreamFixtureCount = 5;\n",
    );
    Ok(output)
}
